"""สร้างไฟล์ประกอบ (ข้อมูลสมมติ) ของตัวอย่าง Skill 5 แบบ → content/skills/examples/<slug>/
Usage: python3 scripts/skills/make_samples.py   (PDF สร้างต่อด้วย node scripts/skills/make-samples.mjs)
ข้อมูลทั้งหมดเป็นตัวอย่างเพื่อการเรียน ไม่ใช่ข้อมูลขององค์กรใด"""
import os
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment
from docx import Document
from docx.shared import Pt

ROOT = os.path.join(os.path.dirname(__file__), '..', '..', 'content', 'skills', 'examples')
NOTE = 'ข้อมูลตัวอย่างเพื่อการเรียน (สมมติ) · แทนด้วยไฟล์จริงขององค์กรก่อนใช้งาน'
HEAD = Font(bold=True, color='FFFFFF')
FILL = PatternFill('solid', fgColor='2557E0')


def sheet(wb, title, header, rows, widths=None, first=False):
    ws = wb.active if first else wb.create_sheet()
    ws.title = title
    ws.append(header)
    for c in ws[1]:
        c.font, c.fill, c.alignment = HEAD, FILL, Alignment(vertical='center', wrap_text=True)
    for r in rows:
        ws.append(r)
    for i, w in enumerate(widths or [18] * len(header)):
        ws.column_dimensions[chr(65 + i)].width = w
    ws.freeze_panes = 'A2'
    return ws


def note_sheet(wb):
    ws = wb.create_sheet('หมายเหตุ')
    ws.append([NOTE])
    ws.column_dimensions['A'].width = 80


def save(wb, slug, name):
    d = os.path.join(ROOT, slug)
    os.makedirs(d, exist_ok=True)
    wb.properties.creator = 'Copilot AI Agents for Work'
    wb.save(os.path.join(d, name))


def doc(slug, name, title, blocks):
    d = Document()
    st = d.styles['Normal']
    st.font.name, st.font.size = 'Tahoma', Pt(11)
    d.core_properties.author = 'Copilot AI Agents for Work'
    d.add_heading(title, 0)
    d.add_paragraph(NOTE).italic = True
    for kind, text in blocks:
        if kind == 'h':
            d.add_heading(text, 1)
        elif kind == 'h2':
            d.add_heading(text, 2)
        elif kind == 'li':
            d.add_paragraph(text, style='List Number')
        elif kind == 'b':
            d.add_paragraph(text, style='List Bullet')
        elif kind == 't':
            rows = text
            t = d.add_table(rows=len(rows), cols=len(rows[0]))
            t.style = 'Table Grid'
            for i, r in enumerate(rows):
                for j, v in enumerate(r):
                    t.cell(i, j).text = str(v)
        else:
            d.add_paragraph(text)
    p = os.path.join(ROOT, slug)
    os.makedirs(p, exist_ok=True)
    d.save(os.path.join(p, name))


