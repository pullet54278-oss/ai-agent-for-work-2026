// คำแนะนำสุขภาพตามวัย (สรุปจาก WHO 2019/2020, American Academy of Sleep Medicine/AAP 2016, กรมอนามัย กระทรวงสาธารณสุข)
// เป็นแนวทางทั่วไป ไม่แทนคำแนะนำของแพทย์ที่ดูแลเด็ก

export interface AdviceItem {
  icon: string
  title: string
  text: string
}

export interface AdviceGroup {
  label: string
  items: AdviceItem[]
  source: string
}

/** คำแนะนำตามอายุ (เดือน) · g6pd = เพิ่มข้อควรระวังสำหรับภาวะพร่องเอนไซม์ G-6-PD */
export function adviceFor(ageMonths: number, g6pd = false): AdviceGroup {
  const y = ageMonths / 12
  const items: AdviceItem[] = []
  let label: string

  if (y < 5) {
    label = 'วัยอนุบาล (3–5 ปี)'
    items.push(
      { icon: '😴', title: 'นอน 10–13 ชม./วัน', text: 'รวมนอนกลางวัน เข้านอนและตื่นเวลาเดิมทุกวัน' },
      { icon: '🏃', title: 'เคลื่อนไหว ≥ 3 ชม./วัน', text: 'มีช่วงที่เล่นจนเหนื่อยหอบอย่างน้อย 60 นาที ไม่นั่งนิ่งนานเกิน 1 ชม.' },
      { icon: '📱', title: 'หน้าจอไม่เกิน 1 ชม./วัน', text: 'ยิ่งน้อยยิ่งดี ดูพร้อมผู้ใหญ่ และงดจอ 1 ชม. ก่อนนอน' },
    )
  } else if (y < 13) {
    label = y < 6 ? 'ช่วงเปลี่ยนเข้าวัยเรียน (5–6 ปี)' : 'วัยเรียน (6–12 ปี)'
    items.push(
      { icon: '😴', title: 'นอน 9–12 ชม./คืน', text: 'เข้านอนก่อน 3 ทุ่ม งดจอและเครื่องดื่มมีคาเฟอีนก่อนนอน' },
      { icon: '🏃', title: 'ออกกำลังกาย ≥ 60 นาที/วัน', text: 'ระดับปานกลางถึงหนัก (วิ่ง ปั่นจักรยาน ว่ายน้ำ) และเล่นที่ใช้กล้ามเนื้อ/กระดูก เช่น กระโดด ปีนป่าย อย่างน้อย 3 วัน/สัปดาห์' },
      { icon: '📱', title: 'จอเพื่อความบันเทิงไม่เกิน 2 ชม./วัน', text: 'ไม่รวมการเรียน พักสายตาทุก 20–30 นาที' },
      { icon: '👀', title: 'ตรวจสายตาและการได้ยินปีละครั้ง', text: 'สังเกตการหรี่ตา ดูใกล้ ปวดหัว หรือเรียนตามไม่ทัน' },
    )
  } else {
    label = 'วัยรุ่น (13 ปีขึ้นไป)'
    items.push(
      { icon: '😴', title: 'นอน 8–10 ชม./คืน', text: 'วัยรุ่นมักนอนดึก ช่วยวางกติกาเวลาเลิกใช้จอ' },
      { icon: '🏃', title: 'ออกกำลังกาย ≥ 60 นาที/วัน', text: 'รวมการฝึกกล้ามเนื้อ 3 วัน/สัปดาห์' },
      { icon: '🧠', title: 'สุขภาพใจ', text: 'พูดคุยเรื่องเพื่อน การเรียน ร่างกายที่เปลี่ยนแปลง และการใช้โซเชียลมีเดีย' },
    )
  }

  items.push(
    { icon: '🥦', title: 'อาหารครบ 5 หมู่ ผัก-ผลไม้ทุกมื้อ', text: 'นมจืดวันละ 2–3 แก้ว ไข่วันละฟอง เนื้อสัตว์/ตับ/เลือด ช่วยเรื่องธาตุเหล็ก ลดน้ำหวาน ขนมกรุบกรอบ และของทอด' },
    {
      icon: '🦷', title: 'แปรงฟันวันละ 2 ครั้ง · พบทันตแพทย์ทุก 6 เดือน',
      text: y < 6
        ? 'ยาสีฟันฟลูออไรด์ 1,000 ppm ขนาดเมล็ดข้าวโพด ผู้ใหญ่แปรงซ้ำให้'
        : 'ยาสีฟันฟลูออไรด์ 1,450 ppm · เคลือบหลุมร่องฟันกรามแท้ซี่แรก (ขึ้นราว 6 ปี)',
    },
    { icon: '📏', title: 'ชั่งน้ำหนัก-วัดส่วนสูงทุก 6 เดือน', text: 'บันทึกในแอปเพื่อดูกราฟ · วัย 4 ปีจนถึงก่อนวัยรุ่นควรสูงขึ้นราว 5–6 ซม./ปี' },
    { icon: '🛟', title: 'ความปลอดภัย', text: 'ฝึกว่ายน้ำให้เป็น ใส่หมวกกันน็อกเมื่อซ้อนจักรยานยนต์/ปั่นจักรยาน นั่งคาร์ซีทหรือบูสเตอร์จนสูง 135 ซม.' },
  )
  if (g6pd) {
    items.push({ icon: '⚠️', title: 'G-6-PD', text: 'แจ้งครู โรงเรียน และแพทย์ทุกครั้ง · ห้ามลูกเหม็น ถั่วปากอ้า และยาในรายการห้ามใช้ · ปัสสาวะสีโค้ก ตัวเหลือง ซีด ให้ไปโรงพยาบาลทันที' })
  }

  return { label, items, source: 'WHO 2019/2020 · AAP/AASM 2016 · กรมอนามัย' }
}
