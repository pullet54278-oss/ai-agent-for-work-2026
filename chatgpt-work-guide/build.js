// Regenerate content.js from content.md: `node build.js`
const fs = require('fs');
const path = require('path');
const md = fs.readFileSync(path.join(__dirname, 'content.md'), 'utf8');
fs.writeFileSync(path.join(__dirname, 'content.js'), '// Generated by build.js from content.md — edit content.md, then run `node build.js`\nwindow.MANUAL_MD = ' + JSON.stringify(md) + ';\n');
console.log('content.js written');
