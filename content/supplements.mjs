// ---------------------------------------------------------------- Module (chapter opening) pages
function moduleSupp(ch, agentsInCh, wfSteps) {
  const assist = agentsInCh.filter(a => a.readiness === 'assist');
  const first = assist[0] || agentsInCh[0];
  const deep = [
    `บทนี้ตั้งเป้าการเรียนรู้ ${ch.goals.length} ข้อ: ${ch.goals.join(' / ')} ให้อ่านหน้าเปิดบทเพื่อเห็นภาพรวม แล้วเลือกเรียนหน้าที่ตรงกับงานของคุณก่อนได้`,
  ];
  if (agentsInCh.length) deep.push(`มี Agent ${agentsInCh.length} ตัว (${agentsInCh.map(a => a.name).join(', ')}) ในจำนวนนี้ ${assist.length} ตัวเป็น Copilot-assisted ซึ่งเริ่มใช้ได้ทันที ตัวที่เหลือต้องวางแผนเชื่อมระบบหรือเป็นการออกแบบเชิงแนวคิด`);
  if (wfSteps) deep.push(`ห่วงโซ่ขั้นตอนงานมี ${wfSteps.length} ขั้น ขั้นที่มีชื่อ Agent คือจุดที่มี Agent ช่วย ขั้นที่ระบุ "ใช้ Prompt ทั่วไป" ให้ใช้ Prompt Mode (บทที่ 2) แทน`);
  return {
    deep,
    example: [first ? `จุดเริ่มที่แนะนำ: ${first.name} — ${first.short} ใช้ข้อมูล ${first.inputs.join(', ')} ซึ่งมักมีอยู่แล้วในงานประจำ จึงเห็นผลเร็วและตรวจได้ง่าย` : 'บทนี้เน้นความรู้พื้นฐาน ให้ทดลอง Prompt ในแต่ละหน้ากับงานจริงของคุณ 1 งาน'],
    workshop: [
      'อ่านกล่อง "เตรียมก่อนเรียน" แล้วเตรียมไฟล์ตัวอย่างอย่างน้อย 1 ไฟล์ (ตัดข้อมูลลับออก)',
      wfSteps ? 'จับคู่ห่วงโซ่ขั้นตอนงานกับงานที่คุณรับผิดชอบ วงขั้นที่ใช้เวลามากที่สุด' : 'จดงานที่คุณทำซ้ำทุกสัปดาห์ 3 งาน แล้วดูว่าหน้าใดในบทนี้เกี่ยวข้อง',
      first ? `เปิดหน้า ${first.name} แล้วทำ Workshop ในหน้านั้นให้ครบ 1 รอบ` : 'ทำ Prompt ที่ใช้ได้ทันทีในหน้าของบทนี้อย่างน้อย 1 Prompt',
      'กลับมาทบทวนเป้าหมายการเรียนรู้ทั้งหมด และทำเครื่องหมายเรียนแล้วเมื่อทำได้จริง'
    ],
    verify: [...ch.goals.map(g => `ทำได้: ${g}`), 'รู้ว่า Agent ตัวใดในบทนี้ใช้กับงานของตนได้ทันที และตัวใดต้องรอระบบ']
  };
}

